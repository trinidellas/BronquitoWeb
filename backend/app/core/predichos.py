"""
Valores predichos que el equipo usa para calcular el nivel automático de
resistencia: S = 0,6·%PIM + 0,4·%FVC. Se recalculan en cada pedido de
`GET /dispositivo/frecuencia`, así se actualizan solos con la edad.

- FVC: GLI Global 2022, la ecuación sin etnia (Bowerman et al., "A
  Race-neutral Approach to the Interpretation of Lung Function
  Measurements", AJRCCM 2023). Edad 3 a 95 años.
      FVC = exp(a0 + a1·ln(altura_cm) + a2·ln(edad) + Mspline(edad))
  Los coeficientes son los del paquete de R `rspiro` (getLMS_GLIgl.R) y las
  tablas Mspline son las oficiales de la GLI (gli_global_lookuptables_dec6.xlsx,
  hojas "Male FVC" y "Female FVC"), una fila cada 0,25 años. Entre dos filas
  se interpola linealmente.
- PIM: Evans y Whitelaw (2009), con la edad en años:
      hombres 120 − 0,41·edad      mujeres 108 − 0,61·edad

Sexo "X": el médico elige en la web qué ecuación usar (la de hombre o la de
mujer) y se aplica a las dos. Si no eligió, los dos predichos van en null.
"""

from datetime import date
from math import exp, log

from sqlalchemy.orm import Session

from app.core.timezone import hoy_argentina
from app.models.configuracion_dispositivo import EcuacionPredichos
from app.models.paciente import Paciente

EDAD_MIN_GLI = 3.0
EDAD_MAX_GLI = 95.0
PASO_TABLA = 0.25

# (a0, a1, a2) de la mediana de FVC.
_COEF_FVC = {
    "M": (-12.629131, 2.727421, 0.009174),
    "F": (-12.055901, 2.621579, -0.035975),
}


def edad_en_anios(nacimiento: date, hoy: date) -> float:
    """Edad con decimales (la tabla de GLI va de a 0,25 años)."""
    return (hoy - nacimiento).days / 365.25


def _mspline(tabla: tuple[float, ...], edad: float) -> float:
    posicion = (edad - EDAD_MIN_GLI) / PASO_TABLA
    i = min(int(posicion), len(tabla) - 2)
    fraccion = posicion - i
    return tabla[i] + (tabla[i + 1] - tabla[i]) * fraccion


def fvc_predicha(edad: float, altura_cm: float, sexo: str) -> float | None:
    """FVC predicha en litros, o None si la edad o la altura no sirven."""
    if sexo not in _COEF_FVC or not (EDAD_MIN_GLI <= edad <= EDAD_MAX_GLI) or not altura_cm or altura_cm <= 0:
        return None
    a0, a1, a2 = _COEF_FVC[sexo]
    tabla = MSPLINE_FVC_HOMBRE if sexo == "M" else MSPLINE_FVC_MUJER
    return exp(a0 + a1 * log(altura_cm) + a2 * log(edad) + _mspline(tabla, edad))


def pim_predicha(edad: float, sexo: str) -> float | None:
    """PIM predicha en cmH2O (en positivo), o None si no se puede calcular."""
    if edad <= 0:
        return None
    if sexo == "M":
        return 120 - 0.41 * edad
    if sexo == "F":
        return 108 - 0.61 * edad
    return None


def sexo_para_ecuacion(paciente: Paciente, db: Session) -> str | None:
    """'M' o 'F'. Para un paciente "X", la que eligió el médico (o None)."""
    if paciente.sexo in ("M", "F"):
        return paciente.sexo
    eleccion = db.get(EcuacionPredichos, paciente.id_paciente)
    return eleccion.sexo_ecuacion if eleccion else None


def predichos(paciente: Paciente, db: Session, hoy: date | None = None) -> dict:
    """
    Lo que va en `"predichos"`: los dos valores como número (null el que no
    se pueda calcular). Para PIM la edad va en años enteros, como en la
    fórmula de Evans y Whitelaw.
    """
    sexo = sexo_para_ecuacion(paciente, db)
    if sexo is None or paciente.fecha_nacimiento is None:
        return {"fvc_predicha_L": None, "pim_predicha_cmh2o": None}
    edad = edad_en_anios(paciente.fecha_nacimiento, hoy or hoy_argentina())
    fvc = fvc_predicha(edad, paciente.altura_cm, sexo)
    pim = pim_predicha(int(edad), sexo)
    return {
        "fvc_predicha_L": round(fvc, 2) if fvc is not None else None,
        "pim_predicha_cmh2o": round(pim, 1) if pim is not None else None,
    }


